#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn no_duplicate_keys_no_empty_strings_no_emoji() {
        let mut seen = HashSet::new();
        for (k, pt, en) in DOCK_TABLE {
            assert!(seen.insert(*k), "chave duplicada {k}");
            assert!(!pt.is_empty() && !en.is_empty(), "tradução vazia em {k}");
            for s in [pt, en] {
                assert!(s.chars().all(|c| (c as u32) < 0x2190 || c == '\u{2026}'), "emoji/símbolo em {k}");
            }
        }
    }

    #[test]
    fn the_table_translates_in_both_languages() {
        use crate::i18n::{tr_in, Lang};
        assert_eq!(tr_in(Lang::En, "menu.window"), "Window");
        assert_eq!(tr_in(Lang::PtBr, "menu.window"), "Janela");
        assert_eq!(tr_in(Lang::En, "act.edit.undo"), "Undo");
    }

    #[test]
    fn every_registry_action_has_a_label_and_nothing_extra_lingers() {
        let labels: HashSet<String> = DOCK_TABLE.iter().filter(|(k, _, _)| k.starts_with("act.")).map(|(k, _, _)| k.to_string()).collect();
        let defs: HashSet<String> = crate::keymap::actions::ACTIONS.iter().map(|d| d.label_key()).collect();
        let missing: Vec<_> = defs.difference(&labels).collect();
        let extra: Vec<_> = labels.difference(&defs).collect();
        assert!(missing.is_empty(), "ações sem rótulo: {missing:?}");
        assert!(extra.is_empty(), "rótulos sem ação: {extra:?}");
    }
}
