#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn no_duplicate_keys_no_empty_strings_and_no_clash_with_the_main_table() {
        let main: HashSet<&str> = crate::i18n::TABLE.iter().map(|(k, _, _)| *k).collect();
        let mut seen = HashSet::new();
        for (k, pt, en) in LIB_TABLE {
            assert!(seen.insert(*k), "chave duplicada {k}");
            assert!(!main.contains(k), "chave {k} também existe em i18n::TABLE");
            assert!(!pt.is_empty() && !en.is_empty(), "tradução vazia em {k}");
            assert!(k.starts_with("lib."));
        }
    }

    /// Toda chave `"lib.*"` escrita no código do workspace precisa existir na tabela.
    #[test]
    fn every_key_used_in_the_source_is_translated() {
        let sources = [
            include_str!("library_ui/mod.rs"),
            include_str!("library_ui/grid.rs"),
            include_str!("library_ui/side.rs"),
            include_str!("library_ui/details.rs"),
            include_str!("library_ui/dialogs.rs"),
            include_str!("library_ui/jobs.rs"),
            include_str!("library_ui/preview.rs"),
            include_str!("library_ui/widgets.rs"),
            include_str!("library_ui/scenario.rs"),
        ];
        let known: HashSet<&str> = LIB_TABLE.iter().map(|(k, _, _)| *k).collect();
        let mut missing = Vec::new();
        for src in sources {
            let mut rest = src;
            while let Some(i) = rest.find("\"lib.") {
                let tail = &rest[i + 1..];
                if let Some(end) = tail.find('"') {
                    let key = &tail[..end];
                    if key.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '.' || c == '_') && !known.contains(key) {
                        missing.push(key.to_string());
                    }
                    rest = &tail[end..];
                } else {
                    break;
                }
            }
        }
        missing.sort();
        missing.dedup();
        assert!(missing.is_empty(), "chaves sem tradução: {missing:?}");
    }
}
